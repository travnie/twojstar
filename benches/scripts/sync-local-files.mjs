import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const product = process.argv[2];
if (!["codebench", "docbench", "streambench"].includes(product)) {
  throw new Error("Expected one Bench workspace.");
}

const source = join(root, "shared", "local-files.js");
const destination = join(root, product, "public");
await mkdir(destination, { recursive: true });
const contents = await readFile(source, "utf8");
const banner = "// Generated by benches/scripts/sync-local-files.mjs from benches/shared/local-files.js. Do not edit directly.\n";
await writeFile(join(destination, "local-files.js"), banner + contents);
